import { readFileSync } from 'node:fs';
import { join, relative } from 'node:path';
import { Ajv2020 } from 'ajv/dist/2020.js';
import { REPO_ROOT } from './scenarios.js';

// --results lets a caller validate an arbitrary results file (e.g. a temp file
// in a test) without touching the committed snapshot; defaults to the tracked
// results/latest.json that CI validates. Mirrors run.ts's --results flag.
function argValue(flag: string): string | undefined {
  const idx = process.argv.indexOf(flag);
  return idx !== -1 ? process.argv[idx + 1] : undefined;
}
const resultsPath = argValue('--results') ?? join(REPO_ROOT, 'results', 'latest.json');
const resultsLabel = relative(REPO_ROOT, resultsPath) || resultsPath;

const schema = JSON.parse(
  readFileSync(join(REPO_ROOT, 'results', 'results.schema.json'), 'utf8')
);
const results = JSON.parse(readFileSync(resultsPath, 'utf8'));

const ajv = new Ajv2020({ allErrors: true });
const validate = ajv.compile(schema);

if (!validate(results)) {
  for (const error of validate.errors ?? []) {
    console.error(`${error.instancePath || '/'} ${error.message}`);
  }
  process.exit(1);
}

// Guard against committing results from a non-canonical local run. The matrix
// is meant to be regenerated by CI on Ubuntu (see .github/workflows/run-suite.yml);
// a developer's local run leaks machine-specific filesystem paths into adapter
// reason/detail strings. Each signature below matches a home/worktree layout that
// only ever appears off-CI: `/Users/` is a macOS home, `.worktrees/` is a local
// git worktree, and `/home/<user>/` is a Linux dev home. CI runs from
// `/home/runner/...`, which we deliberately allow so honest CI breakage still
// surfaces as legitimate error cells. Catching these keeps a local run from
// clobbering the committed matrix.
const LOCAL_PATH_SIGNATURES: { label: string; pattern: RegExp }[] = [
  { label: 'macOS home path (/Users/…)', pattern: /\/Users\// },
  { label: 'local git worktree path (.worktrees/…)', pattern: /(^|\/)\.worktrees\// },
  // Any Linux home except the GitHub Actions runner's /home/runner/.
  { label: 'non-CI Linux home path (/home/<user>/…)', pattern: /\/home\/(?!runner(?:\/|$))[^/]+\// },
];

function findLocalPathLeaks(node: unknown, path: string, hits: string[]): void {
  if (typeof node === 'string') {
    for (const { label, pattern } of LOCAL_PATH_SIGNATURES) {
      if (pattern.test(node)) {
        hits.push(`${path || '/'} contains a ${label}`);
        break;
      }
    }
  } else if (Array.isArray(node)) {
    node.forEach((child, index) => findLocalPathLeaks(child, `${path}/${index}`, hits));
  } else if (node && typeof node === 'object') {
    for (const [key, child] of Object.entries(node)) {
      findLocalPathLeaks(child, `${path}/${key}`, hits);
    }
  }
}

const leaks: string[] = [];
findLocalPathLeaks(results, '', leaks);
if (leaks.length > 0) {
  console.error(
    `${resultsLabel} looks like a local (non-CI) run — machine-specific paths leaked in:`
  );
  for (const leak of leaks) {
    console.error(`  ${leak}`);
  }
  console.error(
    'Regenerate the matrix from a CI run (run-suite.yml) rather than committing a local run.'
  );
  process.exit(1);
}

console.log(`${resultsLabel} validates against results/results.schema.json`);
